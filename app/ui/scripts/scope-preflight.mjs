// Writes src/tw-preflight.css: Tailwind's preflight (its CSS reset) scoped to
// `.tw`, so it applies only inside the ZenLabs screens (Signal Board, Digests,
// Admin, Login) and not to the radar screens, which rely on browser defaults
// and their own styles.css. Run after upgrading Tailwind:
//   node scripts/scope-preflight.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import postcss from "postcss";

const require = createRequire(import.meta.url);
// The theme values preflight reads, as this repo's tailwind.config.js resolves them.
const THEME = {
  "borderColor.DEFAULT": "#e5e7eb", // gray-200, Tailwind's default border colour
  "fontFamily.sans": '"Plus Jakarta Sans", Inter, system-ui, sans-serif',
  "fontFamily.mono": '"JetBrains Mono", monospace',
};
const src = readFileSync(require.resolve("tailwindcss/src/css/preflight.css"), "utf8")
  // theme('key', fallback...) -> this repo's value, else the fallback; this file is not processed by Tailwind
  .replace(/theme\('([^']*)',\s*([^;]*?)\)(\s*;)/g, (_, key, fallback, end) => (THEME[key] ?? fallback) + end);

// :where() adds no specificity, so `:where(.tw) button` weighs the same as preflight's own
// `button` and the design-system classes (.btn-restricted ...) still override it.
const scope = (sel) => {
  sel = sel.trim();
  if (sel === "html" || sel === ":host" || sel === "body") return ":where(.tw)";
  if (sel === "*") return ":where(.tw), :where(.tw) *";
  return `:where(.tw) ${sel}`;
};

const root = postcss.parse(src);
root.walkRules((rule) => {
  rule.selectors = [...new Set(rule.selectors.flatMap((s) => scope(s).split(", ")))];
});
writeFileSync(
  new URL("../src/tw-preflight.css", import.meta.url),
  "/* Generated by scripts/scope-preflight.mjs — Tailwind preflight scoped to .tw. Do not edit. */\n" + root.toString()
);
console.log("wrote src/tw-preflight.css");
